"""Möbius-equivalence demonstration: when do Lorentz-invariant features
pay off?

Synthetic task: classify a 4-point S² configuration by its Möbius
equivalence class. Each class is generated by picking a "seed"
4-point configuration and applying many random SL(2, ℂ) elements
to it; samples within a class are Möbius-equivalent by construction.

By the fundamental theorem of cross-ratios, the cross-ratio of 4
points on ℂP¹ ≅ S² is the unique conformal invariant that
identifies the Möbius equivalence class (up to S₄ permutation of
the points). So:

- A learner with cross-ratio features (Möbius-invariant) recovers
  the class label trivially.
- A learner with rotation-invariant features (pairwise S² distances)
  cannot in general, because Lorentz boosts distort distances while
  preserving Möbius class.

This is the conformal analog of the perp-coordinate regression task
in `experiments/quasicrystal/`: a clean head-to-head where the
target's natural symmetry group determines which feature family
wins. Demonstrates the value of the Lorentz fallback for any future
data with conformal / hyperbolic origin (EPINET hyperbolic-side
tilings being the use-case in mind).

Output: `experiments/lorentz/checkpoints/mobius_class_bench.json`.
"""

from __future__ import annotations

import json
import math
import os
import time
from pathlib import Path

import numpy as np

from experiments.lorentz.mobius import (
    s2_to_complex, complex_to_s2,
    mobius_apply, sl2c_random, sl2c_from_axis_angle,
    cross_ratio_array, s2_cross_ratio,
)


N_CLASSES = 5
N_SAMPLES_PER_CLASS = 200
TRAIN_FRAC = 0.7


def _generate_seed_configs(n_classes: int, rng: np.random.Generator) -> np.ndarray:
    """Pick `n_classes` seed configurations, each 4 points on S²,
    with deliberately distinct cross-ratios so the classes are
    Möbius-distinguishable.
    """
    seeds = []
    while len(seeds) < n_classes:
        pts = rng.normal(size=(4, 3))
        pts = pts / np.linalg.norm(pts, axis=1, keepdims=True)
        z = s2_to_complex(pts)
        try:
            lam = complex(cross_ratio_array(z))
        except Exception:
            continue
        if not np.isfinite(lam):
            continue
        # Ensure new class is far in cross-ratio space from existing.
        too_close = False
        for s in seeds:
            z0 = s2_to_complex(s)
            lam0 = complex(cross_ratio_array(z0))
            if abs(lam - lam0) < 0.5 or abs(lam - 1.0 / lam0) < 0.5:
                too_close = True
                break
        if not too_close:
            seeds.append(pts)
    return np.stack(seeds)  # (n_classes, 4, 3)


def _sample_from_class(seed_config: np.ndarray, n_samples: int,
                       rng: np.random.Generator,
                       rotation_only: bool = False) -> np.ndarray:
    """Generate `n_samples` 4-point S² configs by applying random
    SL(2, ℂ) elements (or only SU(2) if rotation_only) to `seed_config`.

    With rotation_only=False, samples are Möbius-equivalent
    (distorted by Lorentz boosts). With rotation_only=True, samples
    are merely rotation-equivalent (pairwise distances preserved).
    """
    out = np.zeros((n_samples, 4, 3))
    seed_z = s2_to_complex(seed_config)
    for i in range(n_samples):
        if rotation_only:
            axis = rng.normal(size=3); axis /= np.linalg.norm(axis)
            M = sl2c_from_axis_angle(axis, rng.uniform(0, 2 * math.pi))
        else:
            M = sl2c_random(rng)
        z_t = mobius_apply(M, seed_z)
        out[i] = complex_to_s2(z_t)
    return out


# Features ------------------------------------------------------------------


def pairwise_distance_features(configs: np.ndarray) -> np.ndarray:
    """Pairwise S² (chordal) distances between the 4 points; sorted.

    Rotation-invariant; NOT Möbius-invariant. 6 features per config.
    """
    out = np.zeros((len(configs), 6))
    for k in range(len(configs)):
        p = configs[k]
        d = []
        for i in range(4):
            for j in range(i + 1, 4):
                d.append(np.linalg.norm(p[i] - p[j]))
        out[k] = sorted(d)
    return out


def cross_ratio_features(configs: np.ndarray) -> np.ndarray:
    """Cross-ratio of the 4 points: 2 features per config (real, imag).

    Möbius-invariant (and thus SO(3,1)+-invariant) by construction.
    """
    out = np.zeros((len(configs), 2))
    for k in range(len(configs)):
        lam = complex(s2_cross_ratio(*configs[k]))
        out[k, 0] = lam.real
        out[k, 1] = lam.imag
    return out


def all_six_cross_ratios(configs: np.ndarray) -> np.ndarray:
    """All six S₄-permutation values of the cross-ratio.

    Provides a permutation-invariant representation (since the
    multiset is preserved under any reordering of the 4 points).
    12 features per config (6 cross-ratios × 2 real components).
    """
    out = np.zeros((len(configs), 12))
    for k in range(len(configs)):
        p = configs[k]
        # Six permutations capturing all 6 values:
        # (1,2,3,4), (1,2,4,3), (1,3,2,4), (1,3,4,2), (1,4,2,3), (1,4,3,2)
        perms = [
            (0, 1, 2, 3), (0, 1, 3, 2), (0, 2, 1, 3),
            (0, 2, 3, 1), (0, 3, 1, 2), (0, 3, 2, 1),
        ]
        for j, perm in enumerate(perms):
            lam = complex(s2_cross_ratio(p[perm[0]], p[perm[1]], p[perm[2]], p[perm[3]]))
            out[k, 2 * j] = lam.real
            out[k, 2 * j + 1] = lam.imag
    return out


# Classifier ----------------------------------------------------------------


def _ridge_logreg_fit(X, y, n_classes, lam=0.1, n_iter=400, lr=0.5):
    n, d = X.shape
    W = np.zeros((d, n_classes))
    b = np.zeros(n_classes)
    Y = np.eye(n_classes)[y]
    for _ in range(n_iter):
        z = X @ W + b
        z -= z.max(axis=1, keepdims=True)
        ez = np.exp(z); p = ez / ez.sum(axis=1, keepdims=True)
        W -= lr * (X.T @ (p - Y) / n + lam * W)
        b -= lr * (p - Y).mean(axis=0)
    return W, b


def _acc(W, b, X, y):
    return float(np.mean((X @ W + b).argmax(axis=1) == y))


def _train_test(X, y, frac, rng):
    n = len(y); perm = rng.permutation(n); cut = int(frac * n)
    return X[perm[:cut]], y[perm[:cut]], X[perm[cut:]], y[perm[cut:]]


def _standardize(Xtr, Xte):
    mu = Xtr.mean(axis=0)
    sd = Xtr.std(axis=0); sd = np.where(sd > 1e-12, sd, 1.0)
    return (Xtr - mu) / sd, (Xte - mu) / sd


def evaluate(name: str, X: np.ndarray, y: np.ndarray,
             n_classes: int, seeds=(0, 1, 2, 3, 4)) -> dict:
    runs = []
    for s in seeds:
        rng = np.random.default_rng(s)
        Xtr, ytr, Xte, yte = _train_test(X, y, TRAIN_FRAC, rng)
        Xtr, Xte = _standardize(Xtr, Xte)
        W, b = _ridge_logreg_fit(Xtr, ytr, n_classes)
        runs.append({"acc": _acc(W, b, Xte, yte), "n_feat": X.shape[1]})
    accs = np.array([r["acc"] for r in runs])
    return {
        "name": name, "n_features": X.shape[1],
        "test_acc_mean": float(accs.mean()),
        "test_acc_std": float(accs.std(ddof=1)),
        "per_seed": accs.tolist(),
    }


def main(out_path: str):
    # Generate the synthetic Möbius-equivalence classification dataset.
    print("[bench-mob] generating dataset…")
    rng = np.random.default_rng(123)
    seeds = _generate_seed_configs(N_CLASSES, rng)

    # Two variants of the dataset:
    #   (a) MÖBIUS-equivalent samples within each class.
    #   (b) ROTATION-equivalent samples within each class (control).
    configs_mobius = []
    configs_rotonly = []
    labels = []
    for c in range(N_CLASSES):
        rng_class = np.random.default_rng(100 + c)
        configs_mobius.append(_sample_from_class(seeds[c], N_SAMPLES_PER_CLASS,
                                                  rng_class, rotation_only=False))
        rng_class2 = np.random.default_rng(200 + c)
        configs_rotonly.append(_sample_from_class(seeds[c], N_SAMPLES_PER_CLASS,
                                                   rng_class2, rotation_only=True))
        labels.append(np.full(N_SAMPLES_PER_CLASS, c))
    configs_mobius = np.concatenate(configs_mobius, axis=0)
    configs_rotonly = np.concatenate(configs_rotonly, axis=0)
    y = np.concatenate(labels)

    print(f"[bench-mob] {len(y)} samples × {N_CLASSES} classes")

    # ----------------------------------------------------------------
    # Task A: Möbius-equivalence classification.
    # Class membership is preserved under Lorentz boosts; only Möbius
    # invariants identify it. Distance features see only rotation-
    # equivalence, so they will confuse boost-related configs.
    # ----------------------------------------------------------------
    print("\n[bench-mob] === Task A: Möbius-equivalence classification ===")
    pipelines_A = [
        ("pairwise_distances (rot-inv)", pairwise_distance_features(configs_mobius)),
        ("cross_ratio (Möbius-inv)", cross_ratio_features(configs_mobius)),
        ("all_6_cross_ratios (S₄-sym, Möbius-inv)", all_six_cross_ratios(configs_mobius)),
    ]
    results_A = {}
    for name, X in pipelines_A:
        res = evaluate(name, X, y, N_CLASSES)
        results_A[name] = res
        print(f"  {name:42s} ({X.shape[1]:2d} feat): "
              f"acc {res['test_acc_mean']:.4f} ± {res['test_acc_std']:.4f}")

    # ----------------------------------------------------------------
    # Task B: Rotation-equivalence classification (control).
    # Class members differ only by SO(3) rotation. Distance features
    # are sufficient. Cross-ratio features should ALSO work (cross-
    # ratio is SO(3)-invariant since SO(3) ⊂ Möbius), but they don't
    # uniquely identify a rotation orbit — multiple rotation orbits
    # can share a cross-ratio, so cross-ratio features should
    # underperform here.
    # ----------------------------------------------------------------
    print("\n[bench-mob] === Task B: Rotation-only-equivalence (control) ===")
    pipelines_B = [
        ("pairwise_distances (rot-inv)", pairwise_distance_features(configs_rotonly)),
        ("cross_ratio (Möbius-inv)", cross_ratio_features(configs_rotonly)),
        ("all_6_cross_ratios", all_six_cross_ratios(configs_rotonly)),
    ]
    results_B = {}
    for name, X in pipelines_B:
        res = evaluate(name, X, y, N_CLASSES)
        results_B[name] = res
        print(f"  {name:42s} ({X.shape[1]:2d} feat): "
              f"acc {res['test_acc_mean']:.4f} ± {res['test_acc_std']:.4f}")

    out = {
        "n_classes": N_CLASSES,
        "n_samples_per_class": N_SAMPLES_PER_CLASS,
        "task_A_mobius_equivalence": results_A,
        "task_B_rotation_only": results_B,
    }
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        json.dump(out, f, indent=2)
    print(f"\n[bench-mob] wrote {out_path}")
    return out


if __name__ == "__main__":
    out = Path("experiments/lorentz/checkpoints/mobius_class_bench.json")
    main(str(out))
