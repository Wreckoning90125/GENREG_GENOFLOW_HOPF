"""Cut-and-project icosahedral quasicrystal generator.

Builds the standard primitive icosahedral quasicrystal (P-type) from
6D cubic lattice Z^6 via cut-and-project, with the cut window being
the rhombic triacontahedron (the 6D unit cell projected into the
perpendicular 3D subspace).

This is "rolling our own" because no Python library covers
quasicrystal generation: spglib / pyxtal / spgrep stop at the 230
3D space groups and icosahedral symmetry is incompatible with
translation. The reference texts for the construction are:

  - Levine & Steinhardt 1986 (PRB 34, 596): cut-and-project method
  - Elser 1985, 1986: 6D lattice formulation of icosahedral QCs
  - Senechal 1995, "Quasicrystals and Geometry", Cambridge Univ Press
  - Steurer & Deloudi 2009, "Crystallography of Quasicrystals"

Verification (in `tests/test_qc_canonical.py`) checks the output
against canonical published numerical properties of the icosahedral
QC and uses `mpmath` for exact golden-ratio identities. spgrep is
called separately to verify icosahedral group character tables match
what we extract from the QC vertex orbits.
"""

from __future__ import annotations

import math
import numpy as np
from dataclasses import dataclass


# Golden ratio.
TAU = (1.0 + math.sqrt(5.0)) / 2.0


def _projection_matrices() -> tuple[np.ndarray, np.ndarray]:
    """Standard Elser-type 6D -> 3D + 3D-perp projection matrices.

    The 6 basis vectors of Z^6 project to 6 directions in physical
    space (the 5-fold icosahedral axes) and another 6 directions in
    perp space (also 5-fold axes but in a different orientation).

    Each column of the stacked 6x6 matrix [P_phys; P_perp] is a unit
    6D vector, making [P_phys; P_perp] an orthogonal 6x6 matrix. This
    is what makes the cut-and-project an isometry:
    |n|²_6D = |P_phys n|²_3D + |P_perp n|²_3D for all n ∈ R⁶.

    The 3D-only norm of each column is therefore 1/√2 (not 1, despite
    the form of the matrix entries suggesting otherwise — both halves
    share the unit norm).
    """
    s = 1.0 / math.sqrt(2.0 * (2.0 + TAU))
    P_phys = s * np.array([
        [1.0,  TAU,  0.0, -1.0,  TAU,  0.0],
        [TAU,  0.0,  1.0,  TAU,  0.0, -1.0],
        [0.0,  1.0,  TAU,  0.0, -1.0,  TAU],
    ])
    P_perp = s * np.array([
        [TAU, -1.0,  0.0, -TAU, -1.0,  0.0],
        [-1.0, 0.0,  TAU, -1.0,  0.0, -TAU],
        [0.0,  TAU, -1.0,  0.0, -TAU, -1.0],
    ])
    return P_phys, P_perp


def _window_face_normals_and_dist(P_perp: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Return (n_faces, face_distances) for the rhombic triacontahedron
    window — the 6D unit cube [-½, ½]⁶ projected into perp space.

    The window is a zonotope generated by the 6 column vectors of
    P_perp (each scaled by ½, since the cube is [-½, ½]⁶). It has
    exactly 30 rhombic faces, in 15 antipodal pairs. The face normals
    are along the 15 cross-product directions v_i × v_j for 0 ≤ i < j ≤ 5.

    For each face normal n, the support distance from the origin is
        h(n) = ½ Σ_k |v_k · n|
    (the sup of x·n over the zonotope).

    Returns:
        n_faces: (30, 3) unit face normals (15 distinct axes × 2 signs)
        face_distances: (30,) the support distance for each.
    """
    v = P_perp.T  # (6, 3) — perp-space image of each 6D basis vector
    normals = []
    distances = []
    for i in range(6):
        for j in range(i + 1, 6):
            n = np.cross(v[i], v[j])
            n_norm = np.linalg.norm(n)
            if n_norm < 1e-12:
                continue  # degenerate (parallel v_i, v_j) — shouldn't happen here
            n = n / n_norm
            h = 0.5 * np.sum(np.abs(v @ n))
            normals.append(n)
            distances.append(h)
            normals.append(-n)
            distances.append(h)
    return np.array(normals), np.array(distances)


def _inside_window(perp: np.ndarray, n_faces: np.ndarray, d) -> np.ndarray:
    """Vectorized window test. perp shape (..., 3), n_faces (F, 3),
    d shape (F,) or scalar.

    Returns boolean array of shape perp.shape[:-1] — True where the
    point lies inside every halfspace { x : x · n_f ≤ d_f }.
    """
    proj = np.einsum("...i,fi->...f", perp, n_faces)
    if np.isscalar(d) or np.ndim(d) == 0:
        return np.all(proj <= float(d) + 1e-9, axis=-1)
    return np.all(proj <= d + 1e-9, axis=-1)


@dataclass
class IcosahedralQC:
    """A finite icosahedral quasicrystal generated by cut-and-project."""
    physical: np.ndarray          # (N, 3) vertex positions in physical 3D
    perpendicular: np.ndarray     # (N, 3) perp-space coordinates per vertex
    integer_coords: np.ndarray    # (N, 6) the originating Z^6 lattice point
    P_phys: np.ndarray            # (3, 6)
    P_perp: np.ndarray            # (3, 6)
    cutoff: int                   # the |n_i| <= cutoff range used


def generate(cutoff: int = 4) -> IcosahedralQC:
    """Generate the icosahedral QC vertex set in a cube |n_i| <= cutoff (in 6D).

    Returns ~thousands of vertices for cutoff=4-5; ~tens of thousands
    for cutoff=6-7. Memory cost in the 6D enumeration is (2*cutoff+1)^6.

    The vertices are exactly those n ∈ Z^6 with |n_i| <= cutoff whose
    perp-space projection lies inside the rhombic triacontahedron.
    """
    P_phys, P_perp = _projection_matrices()
    n_faces, d = _window_face_normals_and_dist(P_perp)

    side = 2 * cutoff + 1
    # Enumerate by reshape rather than meshgrid (memory friendlier).
    coords = np.arange(-cutoff, cutoff + 1, dtype=np.int32)
    grids = np.array(np.meshgrid(*([coords] * 6), indexing="ij")).reshape(6, -1).T
    # (side^6, 6) — feasible for cutoff <= 5 (15625 -> 11.4M points at 6).
    perp = grids @ P_perp.T  # (M, 3)
    mask = _inside_window(perp, n_faces, d)
    accepted = grids[mask]
    perp_accepted = perp[mask]
    phys_accepted = accepted @ P_phys.T

    return IcosahedralQC(
        physical=phys_accepted,
        perpendicular=perp_accepted,
        integer_coords=accepted,
        P_phys=P_phys,
        P_perp=P_perp,
        cutoff=cutoff,
    )


def vertex_class(qc: IcosahedralQC, n_classes: int = 6) -> np.ndarray:
    """Classify each vertex by its perp-space position.

    Ground-truth vertex environment classification: in the canonical
    icosahedral QC, the perp-space coordinate ENTIRELY DETERMINES the
    local 3D environment, by the cut-and-project construction. Two
    vertices with the same |perp| and the same orbit under the
    icosahedral group in perp space have the same physical-space
    environment up to icosahedral rotation.

    This function bins vertices by the icosahedral-orbit-invariant
    quantity ||perp|| (which alone classifies environments at this
    coarseness). Returns labels in {0, 1, ..., n_classes-1} based on
    quantiles of ||perp||.

    The classification is inherent to the perp-space window structure;
    a learner that only sees physical-space features must reconstruct
    this from the local 3D geometry, which is the test.
    """
    r_perp = np.linalg.norm(qc.perpendicular, axis=1)
    # Bin by quantile so each class is roughly equally populated.
    quantiles = np.linspace(0, 1, n_classes + 1)[1:-1]
    edges = np.quantile(r_perp, quantiles)
    labels = np.searchsorted(edges, r_perp)
    return labels.astype(np.int32)


def tau_inflation(qc: IcosahedralQC, k: int = 3) -> tuple[np.ndarray, np.ndarray]:
    """Apply the τ^k self-similarity transform.

    The icosahedral QC admits an exact self-similarity: scaling
    physical space by τ^k and perp space by (-1/τ)^k = (-1)^k τ^{-k}
    maps the vertex set to itself (in the infinite-cutoff limit). This
    is a hallmark canonical identity for icosahedral QCs (cf. Levine
    & Steinhardt 1986).

    Returns (phys_inflated, perp_inflated). At finite cutoff some
    vertices map outside the original cutoff; the full identity holds
    only in the infinite limit, but a high fraction of vertices should
    survive at moderate cutoff.
    """
    return TAU**k * qc.physical, ((-1)**k) * (TAU**(-k)) * qc.perpendicular
